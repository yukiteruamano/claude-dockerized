#!/bin/bash
# config-file-lib.sh - the wrapper config file: applying setting.* values,
# loading the global file and profile overlays line by line, saving and
# seeding it. Sourced by lib/config-lib.sh (which keeps the constants,
# shared helpers and parse_config/print_config). Not executable directly;
# no `set -e`: callers own error handling.

# shellcheck disable=SC2034 # settings globals are consumed by the other libs and bin/claude-dockerized

# Check if config file exists
config_exists() {
    [ -f "$CONFIG_FILE" ]
}

# Initialize config file with header
init_config_file() {
    mkdir -p "$CONFIG_DIR"
    _config_template >"$CONFIG_FILE"
    config_success "Created config file at $CONFIG_FILE"
}

# The commented template a new config file starts from.
# Usage: _config_template
_config_template() {
    cat <<'EOF'
# Claude Dockerized User Configuration
# Generated by 'claude-dockerized install' - edit manually or re-run 'claude-dockerized install' to modify

# Settings
# SSH Agent Forwarding (enables git over SSH in container)
# Automatically mounts SSH_AUTH_SOCK socket and passes the environment variable
# setting.ssh_agent_support=false

# GnuPG Agent Forwarding (enables git commit signing with your host keys)
# Shares only the public keyring and the gpg-agent socket; private keys never
# enter the container. Requires a running gpg-agent on the host.
# setting.gpg_agent_support=false

# Allow falling back to the full-control gpg-agent socket when the restricted
# S.gpg-agent.extra socket is unavailable. NOT recommended: the main socket can
# reconfigure the host agent. Default: false (warn and skip instead).
# setting.gpg_allow_main_socket=false

# Launch the host gpg-agent automatically at run time when its socket is
# missing. Default: true. Set to false to only warn and never start it.
# setting.gpg_autostart_agent=true

# Relay the agent socket through a socket on a normal filesystem. Needed when
# socketdir is on tmpfs (/run/user/<uid>/gnupg), which Docker cannot bind.
# Requires `socat` on the host. Default: true.
# setting.gpg_relay=true

# Docker socket (opt-in). Mounting it grants the container full control of the
# host Docker daemon, which is effectively root on the host. Enable only when
# you need Docker-in-Docker / Testcontainers.
# setting.docker_socket=false

# Container network: bridge (default; the host's localhost is out of reach,
# services it publishes on the Docker bridge via host.docker.internal) or host
# (shares the host network namespace).
# setting.network=bridge

# Security policy mode enforced by the mounted native hooks.
# strict = every vendored policy pattern; balanced = drop the noisy
# cloud/dev false positives (default); none = vendored patterns disabled
# (built-in backstops still apply). Remote flows stay allowed in all modes.
# setting.security_policy=balanced

# Runtime hardening profile (opt-in; default off keeps today's behavior).
# standard = init + pids limit + private IPC; strict = standard + read-only
# root filesystem, read-only persistent mounts (plugins, skills, ~/.local/bin,
# project .git hooks/config).
# setting.hardening=off

# Report changes to persistent paths (git hooks/config, ~/.local/bin, plugins,
# MCP servers, ...) after each session; audit log in audit/sessions.jsonl.
# setting.integrity_check=true

# Image build options (applied by `build` / `update`): strip setuid bits,
# leave out the Docker CLI (only needed with docker_socket).
# setting.image_strip_setuid=false
# setting.image_docker_cli=true
# Refuse to build a Claude Code version whose binary sha256 was never recorded
# (accept one explicitly with `build --trust-first-use`).
# setting.require_claude_sha=false

# Optional container resource limits (docker --memory / --cpus). Empty = no limit.
# setting.memory=4g
# setting.cpus=2

# Secrets are per profile (never global): the dotenv file
# ~/.config/claude-dockerized/profiles/<name>/env (mode 600) is loaded with
# docker --env-file. Edit it with: claude-dockerized profile edit <name> env

# Profile used when --profile, CLAUDE_DOCKERIZED_PROFILE and a project bind
# do not select one (empty = default). Change it with: claude-dockerized profile use <name>
# setting.profile=default

# Default model (passed as --model; empty = Claude default, /model still works).
# setting.model=

# Local session-data retention in days (cleanupPeriodDays; empty = Claude default).
# setting.cleanup_days=7

# Native LSP support (binaries + .lsp.json live in the generated home).
# setting.lsp=false

# Language servers for setting.lsp=true (csv: go,ts,python,rust).
# setting.lsp_servers=ts,python

# Native formatters (binaries + enabledPlugins in the generated home).
# setting.formatters=false

# Custom volume mounts (read-only by default)
# Format: mount.<name>=<host_path>:<container_path>[:rw]
# Examples:
#   mount.gitconfig=~/.gitconfig:/home/coder/.gitconfig
#   mount.gitignore_global=~/.config/git/gitignore_global:/home/coder/.config/git/gitignore_global
# NOTE: do NOT mount ~/.ssh (it exposes private keys and is refused). Use
# setting.ssh_agent_support=true: the agent socket plus ~/.ssh/config and
# known_hosts are mounted read-only automatically.

# Secrets live in the profile's env file (dotenv KEY=VALUE, never mounted):
# claude-dockerized profile edit <name> env. Install can add keys without
# ever printing them.
EOF
}

# Print an error once per process (settings are parsed several times per
# command). Usage: config_error_once <id> <message>
config_error_once() {
    case "|${_CONFIG_ERRORED:-}|" in *"|$1|"*) return 0 ;; esac
    _CONFIG_ERRORED="${_CONFIG_ERRORED:-}|$1"
    config_error "$2"
}

# Why <file> cannot be parsed safely, or nothing (status 1): a NUL or another
# control byte (tab and CRLF line endings aside). bash `read` drops NUL bytes
# while grep/sed/awk keep them, so one reader could apply a line another one
# never sees (an overlay key split by a NUL slipping past the T-34 checks).
# Usage: config_file_bad_bytes <file>
config_file_bad_bytes() {
    local n cr
    [ -f "$1" ] || return 1
    n=$(LC_ALL=C tr -dc '\000-\010\013\014\016-\037\177' <"$1" 2>/dev/null | wc -c | tr -d ' ')
    if [ "${n:-0}" -gt 0 ]; then
        echo "it contains NUL or other control bytes"
        return 0
    fi
    cr=$(printf '\r')
    if LC_ALL=C grep -q "$cr." "$1" 2>/dev/null; then
        echo "it contains a carriage return inside a line"
        return 0
    fi
    return 1
}

# Split one config line at its FIRST `=` into _CFG_KEY and _CFG_VALUE, both
# trimmed (the CR of a CRLF ending included); the value keeps every later
# `=` (`k=v=` gives `v=`). Usage: config_split_line <line>
config_split_line() {
    local line="$1"
    _CFG_KEY="${line%%=*}"
    _CFG_VALUE=""
    if [[ "$line" == *=* ]]; then
        _CFG_VALUE="${line#*=}"
    fi
    _CFG_KEY="${_CFG_KEY#"${_CFG_KEY%%[![:space:]]*}"}"
    _CFG_KEY="${_CFG_KEY%"${_CFG_KEY##*[![:space:]]}"}"
    _CFG_VALUE="${_CFG_VALUE#"${_CFG_VALUE%%[![:space:]]*}"}"
    _CFG_VALUE="${_CFG_VALUE%"${_CFG_VALUE##*[![:space:]]}"}"
}

# Read the assignments of <file> into _CFG_KEYS / _CFG_VALUES (blank lines
# and # comments skipped), the one parser every config reader shares.
# Usage: config_read_file <file>
config_read_file() {
    local line
    _CFG_KEYS=()
    _CFG_VALUES=()
    [ -f "$1" ] || return 0
    while IFS= read -r line || [ -n "$line" ]; do
        config_split_line "$line"
        case "$_CFG_KEY" in "" | \#*) continue ;; esac
        _CFG_KEYS+=("$_CFG_KEY")
        _CFG_VALUES+=("$_CFG_VALUE")
    done <"$1"
}

# Last value of <key> in <file>, parsed like the loader does; status 1 when
# the file does not set it or is refused (control bytes).
# Usage: config_file_value <file> <key>
config_file_value() {
    local i found=1 value=""
    [ -f "$1" ] || return 1
    config_file_bad_bytes "$1" >/dev/null && return 1
    config_read_file "$1"
    for i in "${!_CFG_KEYS[@]}"; do
        if [ "${_CFG_KEYS[$i]}" = "$2" ]; then
            value="${_CFG_VALUES[$i]}"
            found=0
        fi
    done
    [ "$found" -eq 0 ] || return 1
    printf '%s' "$value"
}

# Set the boolean global <var> from "true"/"false"; any other value leaves it
# unchanged (so an overlay can tighten as well as loosen a setting) and
# returns 1 (not applied).
# Usage: _config_apply_bool <VAR> <value>
_config_apply_bool() {
    case "$2" in
    true) printf -v "$1" '%s' true ;;
    false) printf -v "$1" '%s' false ;;
    *) return 1 ;;
    esac
}

# Apply one validated setting.<key>=<value> to the global settings. Returns 1
# when the value was not applied (invalid, unknown or removed key).
# Usage: _config_apply_setting <key> <value>
_config_apply_setting() {
    local key="$1" value="$2"
    case "$key" in
    ssh_agent_support) _config_apply_bool SSH_AGENT_SUPPORT "$value" ;;
    gpg_agent_support) _config_apply_bool GPG_AGENT_SUPPORT "$value" ;;
    gpg_allow_main_socket) _config_apply_bool GPG_ALLOW_MAIN_SOCKET "$value" ;;
    gpg_autostart_agent) _config_apply_bool GPG_AUTOSTART_AGENT "$value" ;;
    gpg_relay) _config_apply_bool GPG_RELAY "$value" ;;
    docker_socket) _config_apply_bool DOCKER_SOCKET "$value" ;;
    share_skills) _config_apply_bool SHARE_SKILLS "$value" ;;
    lsp_from)
        case "$value" in
        "" | default) LSP_FROM="$value" ;;
        *) config_warning "Invalid lsp_from '$value' (use default or leave it empty); ignoring"; return 1 ;;
        esac
        ;;
    network)
        case "$value" in
        "" | host | bridge)
            NETWORK="${value:-bridge}"
            if [ -n "$value" ]; then
                NETWORK_EXPLICIT=true
            fi
            ;;
        *) config_warning "Invalid network '$value' (use host|bridge); keeping $NETWORK"; return 1 ;;
        esac
        ;;
    env_file) # secrets are per profile now (migrated by lib/profile-lib.sh)
        [ -z "$value" ] || config_warning "Ignoring setting.env_file: secrets are per profile (edit them with: claude-dockerized profile edit <name> env)"
        ;;
    profile) # default profile name (global config only); empty = default
        if [ -z "$value" ]; then
            DEFAULT_PROFILE=""
        elif profile_name_valid "$value"; then
            DEFAULT_PROFILE="$value"
        else
            config_warning "Invalid profile '$value' in setting.profile; using default"; return 1
        fi
        ;;
    model)
        case "$value" in
        "") CLAUDE_MODEL="" ;;
        *[!A-Za-z0-9._-]*) config_warning "Invalid model '$value' (use letters, numbers, . - or _); ignoring"; return 1 ;;
        *) CLAUDE_MODEL="$value" ;;
        esac
        ;;
    claude_version)
        if [ -z "$value" ] || [[ "$value" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
            CLAUDE_VERSION="$value"
        else
            config_warning "Invalid claude_version '$value' (use X.Y.Z); ignoring"; return 1
        fi
        ;;
    cleanup_days)
        if [ -z "$value" ]; then
            CLEANUP_DAYS=""
        elif [[ "$value" =~ ^[0-9]+$ ]]; then
            CLEANUP_DAYS="$value"
        else
            config_warning "Invalid cleanup_days '$value' (use an integer number of days); ignoring"; return 1
        fi
        ;;
    lsp)
        case "$value" in
        true) LSP_ENABLED=true ;;
        false | "") LSP_ENABLED=false ;;
        *) config_warning "Invalid lsp '$value' (use true|false); ignoring"; return 1 ;;
        esac
        ;;
    lsp_servers)
        case "$value" in
        "") ;;
        *[!A-Za-z0-9_,-]* | *,*,*,*,*) config_warning "Invalid lsp_servers '$value' (use a csv of go,ts,python,rust); ignoring"; return 1 ;;
        *) LSP_SERVERS="$value" ;;
        esac
        ;;
    formatters)
        case "$value" in
        true) FORMATTERS_ENABLED=true ;;
        false | "") FORMATTERS_ENABLED=false ;;
        *) config_warning "Invalid formatters '$value' (use true|false); ignoring"; return 1 ;;
        esac
        ;;
    memory)
        if [ -z "$value" ]; then
            MEMORY=""
        elif [[ "$value" =~ ^[0-9]+[bBkKmMgG]$ ]]; then
            MEMORY="$value"
        else
            config_warning "Invalid memory '$value' (e.g. 4g); ignoring"; return 1
        fi
        ;;
    cpus)
        if [ -z "$value" ]; then
            CPUS=""
        elif [[ "$value" =~ ^[0-9]+(\.[0-9]+)?$ ]]; then
            CPUS="$value"
        else
            config_warning "Invalid cpus '$value' (e.g. 2); ignoring"; return 1
        fi
        ;;
    hardening)
        case "$value" in
        "" | off) HARDENING="off" ;;
        standard | strict) HARDENING="$value" ;;
        *) config_warning "Invalid hardening '$value' (use off|standard|strict); keeping off"; return 1 ;;
        esac
        ;;
    integrity_check)
        case "$value" in
        "" | true) INTEGRITY_CHECK=true ;;
        false) INTEGRITY_CHECK=false ;;
        *) config_warning "Invalid integrity_check '$value' (use true|false); keeping true"; return 1 ;;
        esac
        ;;
    image_strip_setuid) _config_apply_bool IMAGE_STRIP_SETUID "$value" ;;
    image_docker_cli) _config_apply_bool IMAGE_DOCKER_CLI "$value" ;;
    require_claude_sha) _config_apply_bool REQUIRE_CLAUDE_SHA "$value" ;;
    security_policy)
        case "$value" in
        strict | balanced | none) SECURITY_POLICY="$value" ;;
        off) SECURITY_POLICY="none" ;;
        *) config_warning "Invalid security_policy '$value' (use strict|balanced|none); keeping balanced"; return 1 ;;
        esac
        ;;
    websearch_provider | theme) # legacy-migration: removed settings from the previous generation
        config_warning "Ignoring removed setting '$key' (not supported by Claude Code); remove it from $CONFIG_FILE"; return 1
        ;;
    *) return 1 ;;
    esac
}

# Load config file into arrays, preserving each entry's original key suffix so
# save_config can re-emit it unchanged (re-running setup never renames keys).
# One pass: mount.* entries, legacy env.* (ignored with a warning: the
# host-environment passthrough was removed, secrets live in the profile's env
# file; see migrate_legacy_env_vars) and setting.* values. This reads the
# GLOBAL file only (the wizard saves what it returns); runtime commands call
# parse_config, which adds the active profile's overlay on top.
load_config() {
    if ! config_exists; then
        # Defaults are valid: say it once per invocation, as information.
        if [ -z "${_CONFIG_MISSING_NOTED:-}" ]; then
            config_info "No config file yet ($CONFIG_FILE): using defaults. Create it with: claude-dockerized install --only config"
            _CONFIG_MISSING_NOTED=1
        fi
        profile_resolve_env_file
        return 1
    fi

    CUSTOM_MOUNTS=()
    CUSTOM_MOUNT_KEYS=()
    config_reset_settings
    CONFIG_REJECTED=""
    _load_config_file "$CONFIG_FILE" || CONFIG_REJECTED="$CONFIG_FILE"
    profile_resolve_env_file
    return 0
}

# Read one config file into the settings state. With <overlay>=overlay the
# file is a profile overlay: only overlay-safe keys apply, a same-named
# mount.* replaces the global one, and a setting that loosens the global
# security posture is ignored unless the file approves that exact value with
# allow_loosen.<key>=<value> (see profile_overlay_apply_setting). A file with
# NUL or other control bytes is refused as a whole (status 1, one error):
# the tools that read it would not agree on its lines.
# Usage: _load_config_file <file> [overlay]
_load_config_file() {
    local file="$1" mode="${2:-global}" reason i
    if reason=$(config_file_bad_bytes "$file"); then
        config_error_once "bad-bytes:$file" "Ignoring $file: $reason (only tabs and line endings are allowed). Fix it in an editor."
        return 1
    fi
    config_read_file "$file"
    local -a keys=("${_CFG_KEYS[@]}") values=("${_CFG_VALUES[@]}")
    [ "$mode" != overlay ] || profile_collect_approvals
    for i in "${!keys[@]}"; do
        _config_apply_line "${keys[$i]}" "${values[$i]}" "$file" "$mode"
    done
    return 0
}

# Apply one parsed key=value line of <file> (see _load_config_file).
# Usage: _config_apply_line <key> <value> <file> <global|overlay>
_config_apply_line() {
    local key="$1" value="$2" file="$3" mode="$4"
    case "$key" in
    mount.*) _config_apply_mount "${key#mount.}" "$value" "$file" "$mode" ;;
    env.*)
        if [ -n "$value" ] && [ -n "${key#env.}" ]; then
            config_warning "Ignoring legacy '${key#env.}' (env.* passthrough was removed); move the value to the profile's env file instead."
        fi
        ;;
    setting.*)
        if [ "$mode" = overlay ]; then
            profile_overlay_apply_setting "${key#setting.}" "$value" "$file"
        else
            _config_apply_setting "${key#setting.}" "$value" || true
        fi
        ;;
    esac
    return 0
}

# Apply mount.<name>=<spec>, keeping the suffix after "mount." so save_config
# re-emits it unchanged. `mount.<name>=-` in a profile overlay drops that
# global mount (removing access needs no approval); a read-write mount from an
# overlay needs approval. Usage: _config_apply_mount <name> <spec> <file> <mode>
_config_apply_mount() {
    local name="$1" value="$2" file="$3" mode="$4" i replaced=false
    if [ "$value" = - ]; then
        if [ "$mode" = overlay ]; then
            _config_drop_mount "$name"
            PROFILE_DROPPED_MOUNTS+=("$name")
        else
            config_warning "Ignoring mount.$name=- in $file: removing a mount only works in a profile overlay"
        fi
        return 0
    fi
    [ -n "$value" ] && [ -n "$name" ] || return 0
    if [ "$mode" = overlay ]; then
        profile_overlay_mount_allowed "$name" "$value" || return 0
        PROFILE_SET_KEYS+=("mount.$name")
        for i in "${!CUSTOM_MOUNT_KEYS[@]}"; do
            if [ "${CUSTOM_MOUNT_KEYS[$i]}" = "$name" ]; then
                CUSTOM_MOUNTS[i]="$value"
                replaced=true
            fi
        done
    fi
    if [ "$replaced" = false ]; then
        CUSTOM_MOUNT_KEYS+=("$name")
        CUSTOM_MOUNTS+=("$value")
    fi
    return 0
}

# Remove every custom mount named <name>, keeping the arrays aligned.
# Usage: _config_drop_mount <name>
_config_drop_mount() {
    local -a keys=() mounts=()
    local i
    for i in "${!CUSTOM_MOUNT_KEYS[@]}"; do
        [ "${CUSTOM_MOUNT_KEYS[$i]}" = "$1" ] && continue
        keys+=("${CUSTOM_MOUNT_KEYS[$i]}")
        mounts+=("${CUSTOM_MOUNTS[$i]}")
    done
    CUSTOM_MOUNT_KEYS=("${keys[@]}")
    CUSTOM_MOUNTS=("${mounts[@]}")
}

# Allocate an unused "customN" key suffix for a new entry, avoiding collisions
# with already-used suffixes passed as arguments.
# Usage: key=$(next_custom_key "${CUSTOM_MOUNT_KEYS[@]}")
next_custom_key() {
    local n=1 existing
    while :; do
        local taken=false
        for existing in "$@"; do
            if [ "$existing" = "custom$n" ]; then
                taken=true
                break
            fi
        done
        if [ "$taken" = false ]; then
            echo "custom$n"
            return 0
        fi
        n=$((n + 1))
    done
}

# Settings save_config writes from the current values; every other line of
# the old file (claude_version, share_skills, lsp_from, unknown keys, the
# user's comments) is kept as it was. Usage: _config_saved_key <key>
_config_saved_key() {
    case "$1" in
    ssh_agent_support | gpg_agent_support | gpg_allow_main_socket | gpg_autostart_agent | gpg_relay | \
        docker_socket | network | security_policy | hardening | integrity_check | image_strip_setuid | \
        image_docker_cli | require_claude_sha | memory | cpus | profile | model | cleanup_days | lsp | \
        lsp_servers | formatters) return 0 ;;
    esac
    return 1
}

CONFIG_KEPT_HEADER="# Kept from the previous file (settings the wizard does not manage, your own comments)"

# Lines of the current global config that save_config does not write itself:
# settings it does not manage and comments that are not part of the
# generated text (<generated> = what is about to be written).
# Usage: _config_kept_lines <generated>
_config_kept_lines() {
    local generated="$1" line
    [ -f "$CONFIG_FILE" ] || return 0
    ! config_file_bad_bytes "$CONFIG_FILE" >/dev/null || return 0
    generated=$(printf '%s\n%s\n' "$generated" "$CONFIG_KEPT_HEADER"; _config_template)
    while IFS= read -r line || [ -n "$line" ]; do
        line="${line%$'\r'}"
        config_split_line "$line"
        case "$_CFG_KEY" in
        # mounts are re-emitted from the arrays; env.*, env_file and the
        # removed settings are obsolete (migrated or ignored), as before.
        "" | mount.* | env.* | setting.env_file | setting.websearch_provider | setting.theme) continue ;;
        \#*) ! grep -qxF -- "$line" <<<"$generated" || continue ;;
        setting.*) ! _config_saved_key "${_CFG_KEY#setting.}" || continue ;;
        esac
        printf '%s\n' "$line"
    done <"$CONFIG_FILE" | awk '!seen[$0]++'
}

# Save current arrays to config file, preserving original key names and
# skipping exact duplicate lines (idempotent across re-runs). Lines the wizard
# does not manage are carried over (_config_kept_lines).
save_config() {
    mkdir -p "$CONFIG_DIR"
    # The default profile is not a wizard setting: an overwrite must not drop
    # it. Read it before the file is truncated below.
    local default_profile="$DEFAULT_PROFILE" generated kept
    [ -n "$default_profile" ] || default_profile=$(profile_config_default)
    generated=$(_config_save_body "$default_profile")
    kept=$(_config_kept_lines "$generated")
    {
        printf '%s\n' "$generated"
        if [ -n "$kept" ]; then
            echo ""
            echo "$CONFIG_KEPT_HEADER"
            printf '%s\n' "$kept"
        fi
    } >"$CONFIG_FILE"

    config_success "Saved configuration to $CONFIG_FILE"
}

# The text save_config writes: every managed setting and the custom mounts.
# Usage: _config_save_body <default_profile>
